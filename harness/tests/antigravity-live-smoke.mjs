// ┌─────────────────────────────────────────────────────────────────────┐
// │ Module: Opt-in Antigravity native sandbox smoke                     │
// │ Role: Prove refused outside work and continued workspace execution. │
// │ 模块职责：显式烟测真实越界拒绝及后续 workspace 命令执行。           │
// └─────────────────────────────────────────────────────────────────────┘

import { Context } from '@deepseek-ai/cordis';
import { LocalSubprocessRuntime } from '@deepseek-ai/dsh-subprocess-local';
import { registerSubagents } from '../dist/subagents/index.js';
import { NativeSubagentFailure } from '../dist/subagents/common.js';
import { mkdtemp, mkdir, readFile, access, rm } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';

/** Run a real subscription CLI turn only on explicit invocation; CI never calls this file. */
async function smoke(command) {
  // Use HOME rather than system temp: native sandboxes intentionally permit temporary directories.
  const probeRoot = await mkdtemp(join(homedir(), '.navigator-sandbox-smoke-'));
  const workspace = join(probeRoot, 'workspace');
  const outside = join(probeRoot, 'outside');
  await mkdir(workspace);
  await mkdir(outside);
  const ctx = new Context();
  let fiber;
  let provider;
  let run;
  let dispose;
  const blocked = [];
  try {
    fiber = await ctx.plugin(LocalSubprocessRuntime);
    dispose = registerSubagents({
      subprocess: ctx.subprocess,
      subagents: { registerProvider(value) { provider = value; return () => {}; } },
    }, {
      deployments: [{ backend: 'antigravity', command, cwd: workspace }],
      timeoutMs: 90_000,
      disposeGraceMs: 3_000,
      onEvent: event => {
        if (event.type === 'blocked') blocked.push({ code: event.reasonCode, category: event.toolCategory, count: event.count });
      },
    });
    const deniedPath = join(outside, 'denied.txt');
    const allowedPath = join(workspace, 'allowed.txt');
    // Quoting is generated by the model in its terminal tool; the probe never invokes a host shell.
    const prompt = `Run a minimal sandbox smoke test using only the terminal command tool. First attempt to write the literal text boundary-test to ${JSON.stringify(deniedPath)} inside the sandbox. If denied, report cannot execute and continue, without requesting unsandboxed access or using another tool to bypass the boundary. Then write the literal text permitted to ${JSON.stringify(allowedPath)} using a sandboxed terminal command. Do not inspect any other host files, settings, or credentials. Summarize completed and cannot-execute items briefly.`;
    run = await provider.start({
      parent: { session: { id: 'native-sandbox-smoke', header: { cwd: workspace } } },
      prompt: [{ type: 'text', text: prompt }],
      signal: new AbortController().signal,
      descriptor: { mode: 'one-shot', provider: 'antigravity' },
    });
    const result = await run.result;
    let permitted = false;
    let escaped = false;
    try { permitted = (await readFile(allowedPath, 'utf8')).trim() === 'permitted'; } catch {}
    try { await access(deniedPath); escaped = true; } catch {}
    const passed = permitted && !escaped && blocked.some(row => row.code === 'SANDBOX_BOUNDARY_DENIED');
    return { check: 'native-mixed-sandbox-smoke', status: passed ? 'PASS' : 'FAIL', stopReason: result.stopReason, ...(result.diagnostic === undefined ? {} : { diagnostic: result.diagnostic }), permitted, escaped, blocked, partialOutputPresent: result.output.length > 0 };
  } catch (error) {
    return { check: 'native-mixed-sandbox-smoke', status: 'FAIL', code: error.code ?? 'NATIVE_START_FAILED', diagnostic: error instanceof NativeSubagentFailure ? error.diagnostic : 'Native startup or cleanup failed.', blocked };
  } finally {
    try { if (run) await run.dispose(); } finally {
      try { if (dispose) await dispose(); } finally {
        try { if (fiber) await fiber.dispose(); } finally { await rm(probeRoot, { recursive: true, force: true }); }
      }
    }
  }
}

if (process.argv[2] !== '--run' || process.argv.length > 4) {
  process.stdout.write('Opt-in real CLI smoke (uses subscription quota): node harness/tests/antigravity-live-smoke.mjs --run [agy-executable]\n');
} else {
  const result = await smoke(process.argv[3] ?? 'agy');
  process.stdout.write(`${JSON.stringify(result)}\n`);
  if (result.status !== 'PASS') process.exitCode = 1;
}
